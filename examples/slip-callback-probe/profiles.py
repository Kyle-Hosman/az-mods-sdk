"""Generate the temporary probe's exact two-image code bindings."""
import argparse
import hashlib
import pathlib
import struct

PROFILES=(
    ("1.30","736bdc9322c00e5770af459c92cace33d8680825c07f00f909f74dfc473a77a6",0x1b99848,0x1b99918,0x1fb5b18,0x1fb5ce8,0x1fb5bb0),
    ("2.00","6577f42532375936c7e3fa830efa35b7daa9cde8e0a265c1fc7143f824321925",0x1d02e48,0x1d02f18,0x2123230,0x2123400,0x21232c8),
)
def generate(root):
    lines=["/* SPDX-License-Identifier: GPL-3.0-only */","/* Generated by profiles.py from the two exact original firmwares. */", "#ifndef SLIP_PROFILES_H", "#define SLIP_PROFILES_H",'#include "binding.h"',"static const struct slip_profile slip_profiles[]={"]
    tags=[]
    for version,digest,cb,ce,dispatch,de,caller in PROFILES:
        data=(root/("EP147-"+version)).read_bytes()
        if hashlib.sha256(data).hexdigest()!=digest:raise ValueError("wrong firmware: "+version)
        if data[:6]!=b"\x7fELF\x02\x01" or struct.unpack_from("<H",data,18)[0]!=183:raise ValueError("not AArch64 ELF")
        offset=struct.unpack_from("<Q",data,32)[0];stride,count=struct.unpack_from("<HH",data,54)
        if stride!=56 or count>64:raise ValueError("invalid ELF program headers")
        rx=[]
        for i in range(count):
            kind,flags,off,rva,_,size,_,_=struct.unpack_from("<IIQQQQQQ",data,offset+i*stride)
            if kind==1 and flags&1:rx.append((off,rva,size))
        h=1469598103934665603
        for off,_,size in rx:
            for byte in data[off:off+size]:h=((h^byte)*1099511628211)&0xffffffffffffffff
        tag="ep147-%016x"%h;tags.append(tag)
        def code(start,end):
            for off,rva,size in rx:
                if rva<=start<end<=rva+size:
                    return hashlib.sha256(data[off+start-rva:off+end-rva]).hexdigest()
            raise ValueError("code outside file-backed executable segment")
        lines.append(' {"%s","%s",{0x%x,%d,"%s"},{0x%x,%d,"%s"},0x%x},'%(version,tag,cb,ce-cb,code(cb,ce),dispatch,de-dispatch,code(dispatch,de),caller))
    lines.extend(["};",'#define SLIP_PROFILE_TAGS "'+tags[0]+'", "'+tags[1]+'"',"#endif",""])
    return "\n".join(lines)
if __name__=="__main__":
    parser=argparse.ArgumentParser();parser.add_argument("firmware_root",type=pathlib.Path);parser.add_argument("--check",action="store_true")
    args=parser.parse_args();output=pathlib.Path(__file__).with_name("profiles.h");text=generate(args.firmware_root)
    if args.check:
        if output.read_text()!=text:raise SystemExit("profile header is stale")
    else:output.write_text(text)
